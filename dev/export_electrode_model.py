"""Write desktop/src/renderer/scene/electrodeModel.ts: a light copy of the Blender exporter's electrode.

The 3-D scene draws one instanced copy of this mesh per EEG electrode (~185 per net), so it is the
exporter's own model (``tit/blender/Electrode.blend``, object ``Electrode``, the one
``tit/blender/electrode_placement.py`` places) with its subdivision modifier dropped and decimated
to a few hundred triangles. Materials are not exported: the scene colours each electrode by its
channel, and its shading comes from the normals written here.

Output frame: +Z is the electrode's axis (the exporter aligns local +Z with the scalp normal), the
base is at z = 0, and the largest radius about the axis is 1 — the renderer scales by the electrode
radius in mm. Normals are per corner, split where faces meet at more than ``SHARP_DEG``, so the rim
stays crisp and the cap stays smooth. Numbers are rounded, so the output is byte-deterministic.

Run (Blender 5.1.0 on the maintainer's Mac; any Blender >= 4.2 with the Decimate modifier works):

    /Applications/Blender.app/Contents/MacOS/Blender --background tit/blender/Electrode.blend \
        --python dev/export_electrode_model.py -- desktop/src/renderer/scene/electrodeModel.ts

``git diff`` after a re-run with the same Blender should be empty.
"""

from __future__ import annotations

import math
import sys

import bpy

TARGET_TRIANGLES = 240
SHARP_DEG = 35.0
OBJECT = "Electrode"


def main(out_path: str) -> None:
    src = bpy.data.objects[OBJECT]
    obj = src.copy()
    obj.data = src.data.copy()
    bpy.context.scene.collection.objects.link(obj)
    for md in list(obj.modifiers):
        obj.modifiers.remove(md)

    obj.data.calc_loop_triangles()
    start = len(obj.data.loop_triangles)
    dec = obj.modifiers.new("decimate", "DECIMATE")
    dec.decimate_type = "COLLAPSE"
    dec.ratio = TARGET_TRIANGLES / start
    dec.use_collapse_triangulate = True
    tri = obj.modifiers.new("triangulate", "TRIANGULATE")
    tri.min_vertices = 4

    depsgraph = bpy.context.evaluated_depsgraph_get()
    mesh = obj.evaluated_get(depsgraph).to_mesh()
    mesh.calc_loop_triangles()

    verts = [v.co.copy() for v in mesh.vertices]
    min_z = min(v.z for v in verts)
    radius = max(math.hypot(v.x, v.y) for v in verts)
    pts = [((v.x) / radius, (v.y) / radius, (v.z - min_z) / radius) for v in verts]

    tris = [tuple(t.vertices) for t in mesh.loop_triangles]

    def face_normal(t):
        a, b, c = (pts[i] for i in t)
        e1 = [b[k] - a[k] for k in range(3)]
        e2 = [c[k] - a[k] for k in range(3)]
        n = [e1[1] * e2[2] - e1[2] * e2[1], e1[2] * e2[0] - e1[0] * e2[2], e1[0] * e2[1] - e1[1] * e2[0]]
        length = math.sqrt(sum(x * x for x in n)) or 1.0
        return [x / length for x in n], length / 2

    faces = [face_normal(t) for t in tris]
    around: dict[int, list[int]] = {}
    for f, t in enumerate(tris):
        for i in t:
            around.setdefault(i, []).append(f)
    cos_sharp = math.cos(math.radians(SHARP_DEG))

    out_pos: list[float] = []
    out_nrm: list[float] = []
    out_idx: list[int] = []
    seen: dict[tuple, int] = {}
    for f, t in enumerate(tris):
        nf = faces[f][0]
        for i in t:
            acc = [0.0, 0.0, 0.0]
            for g in around[i]:
                ng, area = faces[g]
                if sum(nf[k] * ng[k] for k in range(3)) >= cos_sharp:
                    for k in range(3):
                        acc[k] += ng[k] * area
            length = math.sqrt(sum(x * x for x in acc)) or 1.0
            p = tuple(round(x, 4) for x in pts[i])
            n = tuple(round(x / length, 3) for x in acc)
            key = p + n
            if key not in seen:
                seen[key] = len(out_pos) // 3
                out_pos.extend(p)
                out_nrm.extend(n)
            out_idx.append(seen[key])

    height = max(p[2] for p in pts)
    fmt = lambda xs: ",".join(f"{x:g}" for x in xs)  # noqa: E731
    text = f"""// GENERATED by dev/export_electrode_model.py from tit/blender/Electrode.blend ({bpy.app.version_string}).
// Do not edit: re-run the script. Frame: +Z is the electrode axis, base at z = 0, max radius 1.
export const ELECTRODE_MODEL = {{
  /** Triangles: {len(out_idx) // 3} (from {start} in the .blend, subdivision dropped). */
  height: {height:.4f},
  positions: new Float32Array([{fmt(out_pos)}]),
  normals: new Float32Array([{fmt(out_nrm)}]),
  indices: new Uint16Array([{fmt(out_idx)}]),
}};
"""
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"electrode model: {len(out_idx) // 3} triangles, {len(out_pos) // 3} vertices, height {height:.4f} -> {out_path}")


if __name__ == "__main__":
    argv = sys.argv[sys.argv.index("--") + 1 :] if "--" in sys.argv else []
    if len(argv) != 1:
        raise SystemExit("usage: blender --background Electrode.blend --python export_electrode_model.py -- OUT.ts")
    main(argv[0])
