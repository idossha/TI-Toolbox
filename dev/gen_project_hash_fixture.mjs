#!/usr/bin/env node
/**
 * Writes tests/fixtures/project_hash.json: host project directory -> the compose project name
 * (`ti-toolbox-<hash8>`) that every launcher must derive for it. The name is the `tit.project`
 * label and the container-name prefix, so a launcher that computes a different one cannot see,
 * attach to or stop a container another launcher started for the same directory.
 *
 * The reference is written here independently of the three implementations it checks
 * (desktop/src/shared/compose.ts#hash8, tit/launch.py#hash8, loader.sh#project_stack): exact
 * BigInt arithmetic modulo 2^32 instead of Math.imul, over the UTF-16 code units Node's own
 * `utf16le` encoder produces instead of charCodeAt. UTF-16 code units are the reference because
 * the desktop app (Electron, the default launcher) has always hashed them; for every path in the
 * Basic Multilingual Plane they equal Unicode code points, so only astral characters (emoji)
 * distinguish the two rules.
 *
 * ANCHORS are names observed outside this script: one read off a real container the desktop app
 * created, the others printed by the shipping Electron hash8 during the 2026-10-22 launcher audit.
 * Generation fails if the reference disagrees with any of them.
 *
 * Usage: node dev/gen_project_hash_fixture.mjs [--check]
 *   --check  exit 1 if the committed fixture differs from what this script would write.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const OUT = fileURLToPath(new URL("../tests/fixtures/project_hash.json", import.meta.url));
const MASK = (1n << 32n) - 1n;

/** The UTF-16 code units of `text`, read back from Node's utf16le encoder (little-endian pairs). */
function utf16Units(text) {
  const bytes = Buffer.from(text, "utf16le");
  const units = [];
  for (let i = 0; i < bytes.length; i += 2) units.push(BigInt(bytes[i] | (bytes[i + 1] << 8)));
  return units;
}

const mul32 = (a, b) => (a * b) & MASK;

function referenceName(text) {
  const units = utf16Units(text);
  const length = BigInt(units.length);
  let h1 = 0xdeadbeefn ^ length;
  let h2 = 0x41c6ce57n ^ length;
  for (const unit of units) {
    h1 = mul32(h1 ^ unit, 2654435761n);
    h2 = mul32(h2 ^ unit, 1597334677n);
  }
  const mixed = mul32(h1 ^ (h1 >> 16n), 2246822507n) ^ mul32(h2 ^ (h2 >> 13n), 3266489909n);
  return `ti-toolbox-${mixed.toString(16).padStart(8, "0")}`;
}

const ANCHORS = {
  // `docker inspect` of the container the desktop app created for this directory, 2026-09-07.
  "/Users/idohaber/datasets/000": "ti-toolbox-fad740e5",
  // Printed by desktop/src/shared/compose.ts#hash8 in the 2026-10-22 launcher audit.
  "/Users/ido/datasets/000": "ti-toolbox-87db4d88",
  "/Users/José/data": "ti-toolbox-41bfbb43",
  "/Users/ido/\u{1F4C1} data": "ti-toolbox-b3e9bd2b",
  "/tmp/x\u{1F600}y": "ti-toolbox-2295c464",
};

const ROWS = [
  ["real container (ASCII)", "/Users/idohaber/datasets/000"],
  ["ASCII", "/Users/ido/datasets/000"],
  ["spaces", "/Users/x/My Data"],
  ["spaces, longer", "/Users/ido/My Project Data"],
  ["Latin-1 accent", "/Users/José/data"],
  ["NFC é (one code point)", "/Users/ido/Donn\u00e9es"],
  ["NFD e + combining acute (two code points)", "/Users/ido/Donne\u0301es"],
  ["CJK", "/data/\u6570\u636e"],
  ["CJK, short", "/tmp/\u65e5\u672c"],
  ["emoji folder (astral: two UTF-16 units)", "/Users/ido/\u{1F4C1} data"],
  ["emoji inside a name", "/tmp/x\u{1F600}y"],
  ["Windows drive path", "C:\\Users\\me\\proj"],
  ["Windows drive path with a space", "C:\\Users\\me\\My Project"],
  ["WSL share (UNC)", "\\\\wsl.localhost\\Ubuntu\\home\\me\\p"],
];

function build() {
  for (const [path, name] of Object.entries(ANCHORS)) {
    const got = referenceName(path);
    if (got !== name) throw new Error(`reference disagrees with an observed name for ${JSON.stringify(path)}: ${got} != ${name}`);
  }
  const fixture = {
    _comment:
      "Generated by `node dev/gen_project_hash_fixture.mjs`; do not edit. Host project directory -> " +
      "compose project name (`tit.project` label, container-name prefix). Hash over UTF-16 code units.",
    rows: ROWS.map(([label, path]) => ({ label, path, name: referenceName(path) })),
  };
  // Non-ASCII as \u escapes so NFC and NFD rows read differently in any editor.
  return `${JSON.stringify(fixture, null, 2).replace(/[\u007f-\uffff]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, "0")}`)}\n`;
}

const text = build();
if (process.argv.includes("--check")) {
  let committed = "";
  try {
    committed = readFileSync(OUT, "utf8");
  } catch {
    console.error(`missing ${OUT}; run node dev/gen_project_hash_fixture.mjs`);
    process.exit(1);
  }
  if (committed !== text) {
    console.error(`${OUT} is stale; run node dev/gen_project_hash_fixture.mjs`);
    process.exit(1);
  }
  console.log("project_hash.json is current");
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT}`);
}
